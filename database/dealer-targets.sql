CREATE TABLE IF NOT EXISTS DealerMonthlyTargets (
  Month CHAR(7) NOT NULL,
  DealerID VARCHAR(20) NOT NULL,
  TargetAmount DECIMAL(16,2) NOT NULL,
  IncrementPercent DECIMAL(9,2) NULL,
  Enabled TINYINT(1) NOT NULL DEFAULT 1,
  DeductReturns TINYINT(1) NOT NULL DEFAULT 1,
  TierMode VARCHAR(20) NOT NULL DEFAULT 'HIGHEST',
  TiersJson LONGTEXT NOT NULL,
  Notes VARCHAR(500) NOT NULL DEFAULT '',
  Version INT NOT NULL DEFAULT 1,
  CreatedAt DATETIME NOT NULL,
  CreatedBy VARCHAR(120) NOT NULL,
  UpdatedAt DATETIME NOT NULL,
  UpdatedBy VARCHAR(120) NOT NULL,
  PRIMARY KEY (Month, DealerID)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
